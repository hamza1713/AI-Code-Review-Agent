// Generates src/theme.css from Tailwind's palette.
//
// Dark is the original palette. Light mirrors each hue's scale (50<->950,
// 100<->900, ...), so existing classes such as `bg-slate-900 text-slate-100`
// or `text-rose-300` keep their contrast in both themes without rewriting
// every component. Re-run after upgrading Tailwind:
//   node scripts/generate-theme.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(here, '..', 'node_modules', 'tailwindcss', 'theme.css'), 'utf8');

const HUES = ['slate', 'indigo', 'rose', 'emerald', 'amber', 'sky', 'cyan', 'blue', 'orange', 'purple', 'pink', 'red', 'green', 'violet', 'yellow', 'teal'];
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];

const palette = {};
for (const match of source.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) {
  const [, hue, shade, value] = match;
  if (HUES.includes(hue)) (palette[hue] ??= {})[shade] = value.trim();
}

const theme = [];
const dark = [];
const light = [];
for (const hue of HUES) {
  for (const [i, shade] of SHADES.entries()) {
    theme.push(`  --color-${hue}-${shade}: var(--p-${hue}-${shade});`);
    dark.push(`  --p-${hue}-${shade}: ${palette[hue][shade]};`);
    light.push(`  --p-${hue}-${shade}: ${palette[hue][SHADES[SHADES.length - 1 - i]]};`);
  }
}

const semanticDark = `
  --canvas: #0a0c10;
  --surface: #12151c;
  --raised: #181c26;
  --line: #262c3a;
  --ink: #e2e8f0;
  --ink-muted: #94a3b8;
  --p-white: #ffffff;
  --p-black: #000000;
  --focus: #a5b4fc;
  color-scheme: dark;`;
const semanticLight = `
  --canvas: #f6f7fb;
  --surface: #ffffff;
  --raised: #eef1f7;
  --line: #d9dee8;
  --ink: #111827;
  --ink-muted: #4b5563;
  --p-white: #0f172a;
  --p-black: #ffffff;
  --focus: #4338ca;
  color-scheme: light;`;

const css = `/* Generated by scripts/generate-theme.mjs. Do not edit by hand. */
@theme {
  --font-sans: "Inter", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
  --font-mono: "JetBrains Mono", "Fira Code", Consolas, Menlo, monospace;
  --color-canvas: var(--canvas);
  --color-surface: var(--surface);
  --color-raised: var(--raised);
  --color-line: var(--line);
  --color-ink: var(--ink);
  --color-ink-muted: var(--ink-muted);
  --color-white: var(--p-white);
  --color-black: var(--p-black);
${theme.join('\n')}
}

:root {${semanticDark}
${dark.join('\n')}
}

@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {${semanticLight}
${light.join('\n')}
  }
}

:root[data-theme="light"] {${semanticLight}
${light.join('\n')}
}
`;

writeFileSync(join(here, '..', 'src', 'theme.css'), css);
console.log(`theme.css written: ${HUES.length} hues`);
